#!/usr/bin/env node

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pduRoot = resolve(root, 'src/pdu_msgs');
const outputPath = resolve(root, 'src/browser/generatedConverterRegistry.js');

async function collectConverters(directory) {
    const converters = [];
    for (const entry of await readdir(directory, { withFileTypes: true })) {
        const path = resolve(directory, entry.name);
        if (entry.isDirectory()) {
            converters.push(...await collectConverters(path));
            continue;
        }
        const match = /^pdu_(cdr_)?conv_(.+)\.js$/.exec(entry.name);
        if (!match) {
            continue;
        }
        const pkg = relative(pduRoot, directory).split(sep).join('/');
        const encoding = match[1] ? 'cdr' : 'hako';
        const name = match[2];
        converters.push({
            key: `${encoding}:${pkg}/${name}`,
            specifier: `../pdu_msgs/${pkg}/${entry.name}`,
        });
    }
    return converters;
}

function renderRegistry(converters) {
    const entries = converters
        .sort((left, right) => left.key.localeCompare(right.key))
        .map(({ key, specifier }) => `    ${JSON.stringify(key)}: () => import(${JSON.stringify(specifier)}),`)
        .join('\n');

    return `// Generated by scripts/generate-browser-converter-registry.mjs. Do not edit.\n` +
        `// Every import specifier must stay literal so browser bundlers can emit lazy chunks.\n\n` +
        `export const browserConverterLoaders = Object.freeze({\n${entries}\n});\n\n` +
        `export function getBrowserConverterLoader(encoding, pkg, name) {\n` +
        `    return browserConverterLoaders[\`${'${encoding}'}:${'${pkg}'}/${'${name}'}\`];\n` +
        `}\n`;
}

const generated = renderRegistry(await collectConverters(pduRoot));
if (process.argv.includes('--check')) {
    let current = '';
    try {
        current = await readFile(outputPath, 'utf8');
    } catch {
        // Report the same actionable failure as stale generated content.
    }
    if (current !== generated) {
        console.error('Browser converter registry is stale. Run npm run generate:browser-registry.');
        process.exit(1);
    }
    console.log('Browser converter registry is up to date.');
} else {
    await writeFile(outputPath, generated, 'utf8');
    console.log(`Generated ${relative(root, outputPath)}.`);
}
